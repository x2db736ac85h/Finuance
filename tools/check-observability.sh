#!/usr/bin/env bash
# Checks the observability chart (PLAN 17.3, 17.4): the dashboards equal what their generator
# writes, the chart lints and renders with every values file and validates with kubeconform, the
# rendered alert rules pass `promtool check rules` and the unit tests in tests/rules.test.yaml, and
# every metric a dashboard or rule uses exists: in metrics.txt (what the api and worker register,
# kept current by TestMetricNames) or external-metrics.txt (CloudNativePG, the Barman Cloud plugin,
# kube-state-metrics, the Go collectors).
# Needs helm, kubeconform, mikefarah's yq ($YQ), node and promtool ($PROMTOOL; by default the
# pinned prom/prometheus image through Docker).
set -euo pipefail
cd "$(dirname "$0")/.."
K8S=1.33.0
YQ=${YQ:-yq}
CRDS='https://raw.githubusercontent.com/datreeio/CRDs-catalog/main/{{.Group}}/{{.ResourceKind}}_{{.ResourceAPIVersion}}.json'
PROM_IMAGE=prom/prometheus:v3.15.0@sha256:efd719c99d83b060d9daefdcf00360461adf279f45ef5391f8d111892118753e
chart=deploy/k8s/observability
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# promtool <args…> with paths inside $work
promtool() {
  if [ -n "${PROMTOOL:-}" ]; then (cd "$work" && "$PROMTOOL" "$@"); return; fi
  docker run --rm --user "$(id -u):$(id -g)" -v "$work:/w:ro" -w /w --entrypoint promtool "$PROM_IMAGE" "$@"
}

echo "== dashboards are what tools/observability/dashboards.mjs writes"
DASHBOARDS_OUT="$work/dashboards" node tools/observability/dashboards.mjs >/dev/null
diff -r "$work/dashboards" "$chart/files/dashboards" || { echo "check-observability: run node tools/observability/dashboards.mjs and commit"; exit 1; }
echo ok

echo "== chart renders with every values file"
helm lint "$chart" --strict --kube-version "$K8S" | grep -vE '^(==> Linting|\[INFO\]|$|1 chart\(s\) linted)' || true
helm lint "$chart" --strict --kube-version "$K8S" >/dev/null
for v in "" "$chart"/ci/*.yaml; do
  args=(--kube-version "$K8S"); [ -n "$v" ] && args+=(-f "$v")
  helm template obs "$chart" -n monitoring "${args[@]}" >"$work/render.yaml"
  kubeconform -strict -summary -kubernetes-version "$K8S" -schema-location default -schema-location "$CRDS" "$work/render.yaml"
done
# the homelab layering (ADR 0023): generic values, then the example overlay, and locally the private one
H=deploy/environments/homelab
for o in "$H/observability-values.example.yaml" "${FINUANCE_ENV_DIR:-../finuance-env}/homelab/observability-values.yaml"; do
  [ -f "$o" ] || continue
  helm template obs "$chart" -n monitoring --kube-version "$K8S" -f "$H/observability-values.yaml" -f "$o" \
    | kubeconform -strict -summary -kubernetes-version "$K8S" -schema-location default -schema-location "$CRDS" -
done
if helm template obs "$chart" --kube-version "$K8S" --set alerting.email.enabled=true >/dev/null 2>&1; then
  echo "check-observability: the e-mail receiver rendered without an address"; exit 1
fi

echo "== alert rules (promtool)"
helm template obs "$chart" -n monitoring --kube-version "$K8S" -f "$chart/ci/email-values.yaml" >"$work/render-all.yaml"
# RENDER_DIR: the CI helm job's Trivy config scan reads the renders there.
if [ -n "${RENDER_DIR:-}" ]; then mkdir -p "$RENDER_DIR" && cp "$work/render-all.yaml" "$RENDER_DIR/observability.yaml"; fi
helm template obs "$chart" -n monitoring --kube-version "$K8S" >"$work/render.yaml"
"$YQ" 'select(.kind == "PrometheusRule") | .spec' "$work/render.yaml" >"$work/rules.yaml"
cp "$chart/tests/rules.test.yaml" "$work/"
promtool check rules --lint=all --lint-fatal rules.yaml
promtool test rules rules.test.yaml

echo "== the local profile's rules are the chart's (deploy/compose/observability/rules.yaml)"
local_rules=deploy/compose/observability/rules.yaml
{
  echo "# Generated by tools/check-observability.sh from deploy/k8s/observability (ci/compose-values.yaml)."
  echo "# UPDATE=1 tools/check-observability.sh rewrites it."
  helm template obs "$chart" --kube-version "$K8S" -f "$chart/ci/compose-values.yaml" | "$YQ" 'select(.kind == "PrometheusRule") | .spec'
} >"$work/local-rules.yaml"
if [ "${UPDATE:-}" = 1 ]; then cp "$work/local-rules.yaml" "$local_rules"; fi
diff "$work/local-rules.yaml" "$local_rules" || { echo "check-observability: run UPDATE=1 tools/check-observability.sh and commit"; exit 1; }
echo ok

echo "== every metric used exists"
# Queries of the rules and of every dashboard panel. Metric names are the identifiers right before
# a selector's "{"; histogram series fall back to their family name.
{
  "$YQ" '.groups[].rules[].expr' "$work/rules.yaml"
  for f in "$chart"/files/dashboards/*.json; do "$YQ" -p json -o yaml '.. | select(has("expr")) | .expr' "$f"; done
} >"$work/exprs.txt"
grep -oE '[A-Za-z_:][A-Za-z0-9_:]*\{' "$work/exprs.txt" | sed 's/{$//' | sort -u >"$work/used.txt"
"$YQ" '.groups[].rules[] | select(has("record")) | .record' "$work/rules.yaml" | sort -u >"$work/recorded.txt"
known=$(cat <(grep -v '^#' "$chart/metrics.txt") <(grep -v '^#' "$chart/external-metrics.txt") "$work/recorded.txt" | grep -v '^$' | sort -u)
missing=0
while read -r m; do
  family=$(sed -E 's/_(bucket|sum|count)$//' <<<"$m")
  if ! grep -qxF "$m" <<<"$known" && ! grep -qxF "$family" <<<"$known"; then
    echo "check-observability: unknown metric $m"; missing=$((missing + 1))
  fi
done <"$work/used.txt"
[ "$missing" -eq 0 ] || exit 1
echo "ok ($(wc -l <"$work/used.txt") metrics)"
echo "check-observability: ok"
