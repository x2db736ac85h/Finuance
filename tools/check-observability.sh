#!/usr/bin/env bash
# Checks the observability chart (PLAN 17.3, 17.4): the dashboards equal what their generator
# writes, the chart lints and renders with every values file and validates with kubeconform, the
# rendered alert rules pass `promtool check rules` and the unit tests in tests/rules.test.yaml, and
# every metric a dashboard or rule uses exists: in metrics.txt (what the api and worker register,
# kept current by TestMetricNames) or external-metrics.txt (CloudNativePG, the Barman Cloud plugin,
# kube-state-metrics, the Go collectors). For the telemetry chart (PLAN 24.6): Loki accepts its
# configuration, Alloy validates its own, every Alloy file is formatted, and the log stages turn the
# sample lines in deploy/k8s/telemetry/tests into tests/stages.expected (UPDATE=1 rewrites it).
# Needs helm, kubeconform, mikefarah's yq ($YQ), node, Docker (Loki's and Alloy's images, from the
# chart's values) and promtool ($PROMTOOL; by default the pinned prom/prometheus image through Docker).
set -euo pipefail
cd "$(dirname "$0")/.."
K8S=1.33.0
YQ=${YQ:-yq}
# The catalog at one commit (2026-11-20), not its moving main: what the checks validate against
# changes only when this line does. Bump it by hand when a chart brings a newer CRD version.
CRDS='https://raw.githubusercontent.com/datreeio/CRDs-catalog/784ec895547a36e548e6810b41f27baade3a0890/{{.Group}}/{{.ResourceKind}}_{{.ResourceAPIVersion}}.json'
PROM_IMAGE=prom/prometheus:v3.16.0@sha256:e04987641b57704f408e31f6373ba4138ecf27cb4a165d24aabb6c38fddd0f06
chart=deploy/k8s/observability
work=$(mktemp -d)
stages_container=finuance-alloy-stages-$$
trap 'docker rm -f "$stages_container" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

# promtool <args…> with paths inside $work
promtool() {
  if [ -n "${PROMTOOL:-}" ]; then (cd "$work" && "$PROMTOOL" "$@"); return; fi
  docker run --rm --user "$(id -u):$(id -g)" -v "$work:/w:ro" -w /w --entrypoint promtool "$PROM_IMAGE" "$@"
}

echo "== dashboards are what tools/observability/dashboards.mjs writes"
DASHBOARDS_OUT="$work/dashboards" node tools/observability/dashboards.mjs >/dev/null
diff -r "$work/dashboards" "$chart/files/dashboards" || { echo "check-observability: run node tools/observability/dashboards.mjs and commit"; exit 1; }
echo ok

echo "== chart renders with every values file"
helm lint "$chart" --strict --kube-version "$K8S" | grep -vE '^(==> Linting|\[INFO\]|$|1 chart\(s\) linted)' || true
helm lint "$chart" --strict --kube-version "$K8S" >/dev/null
for v in "" "$chart"/ci/*.yaml; do
  args=(--kube-version "$K8S"); [ -n "$v" ] && args+=(-f "$v")
  helm template obs "$chart" -n monitoring "${args[@]}" >"$work/render.yaml"
  kubeconform -strict -summary -kubernetes-version "$K8S" -schema-location default -schema-location "$CRDS" "$work/render.yaml"
done
# the homelab layering (ADR 0023): generic values, then the example overlay, and locally the private one
H=deploy/environments/homelab
for o in "$H/observability-values.example.yaml" "${FINUANCE_ENV_DIR:-../finuance-env}/homelab/observability-values.yaml"; do
  [ -f "$o" ] || continue
  helm template obs "$chart" -n monitoring --kube-version "$K8S" -f "$H/observability-values.yaml" -f "$o" \
    | kubeconform -strict -summary -kubernetes-version "$K8S" -schema-location default -schema-location "$CRDS" -
done
if helm template obs "$chart" --kube-version "$K8S" --set alerting.email.enabled=true >/dev/null 2>&1; then
  echo "check-observability: the e-mail receiver rendered without an address"; exit 1
fi

echo "== alert rules (promtool)"
helm template obs "$chart" -n monitoring --kube-version "$K8S" -f "$chart/ci/email-values.yaml" >"$work/render-all.yaml"
# RENDER_DIR: the CI helm job's Trivy config scan reads the renders there.
if [ -n "${RENDER_DIR:-}" ]; then mkdir -p "$RENDER_DIR" && cp "$work/render-all.yaml" "$RENDER_DIR/observability.yaml"; fi
# every rule group, for the tests (the digest's test data comes every 10 minutes, like its rule evaluations)
helm template obs "$chart" -n monitoring --kube-version "$K8S" --set ingress.traefik.enabled=true \
  --set digest.enabled=true --set digest.evaluationSeconds=600 >"$work/render.yaml"
"$YQ" 'select(.kind == "PrometheusRule") | .spec' "$work/render.yaml" >"$work/rules.yaml"
cp "$chart"/tests/*.test.yaml "$work/"
# the digest's timing is checked on its rendered expression alone (tests/digest-time.test.yaml)
echo 'groups: []' >"$work/no-rules.yaml"
DIGEST_EXPR=$("$YQ" '.groups[].rules[] | select(.alert == "FinuanceDailyDigest") | .expr' "$work/rules.yaml") \
  "$YQ" -i '(.tests[].promql_expr_test[] | select(.expr == "DIGEST_EXPR") | .expr) = strenv(DIGEST_EXPR)' "$work/digest-time.test.yaml"
promtool check rules --lint=all --lint-fatal rules.yaml
promtool test rules rules.test.yaml digest.test.yaml digest-time.test.yaml

echo "== the local profile's rules are the chart's (deploy/compose/observability/rules.yaml)"
local_rules=deploy/compose/observability/rules.yaml
{
  echo "# Generated by tools/check-observability.sh from deploy/k8s/observability (ci/compose-values.yaml)."
  echo "# UPDATE=1 tools/check-observability.sh rewrites it."
  helm template obs "$chart" --kube-version "$K8S" -f "$chart/ci/compose-values.yaml" | "$YQ" 'select(.kind == "PrometheusRule") | .spec'
} >"$work/local-rules.yaml"
if [ "${UPDATE:-}" = 1 ]; then cp "$work/local-rules.yaml" "$local_rules"; fi
diff "$work/local-rules.yaml" "$local_rules" || { echo "check-observability: run UPDATE=1 tools/check-observability.sh and commit"; exit 1; }
echo ok

echo "== every metric used exists"
# Queries of the rules, of the digest's text (its annotations run queries) and of every dashboard
# panel. Metric names are the identifiers right before a selector's "{" (not a template's "{{");
# histogram series fall back to their family name.
{
  "$YQ" '.groups[].rules[].expr' "$work/rules.yaml"
  "$YQ" '.groups[].rules[] | select(has("annotations")) | .annotations[]' "$work/rules.yaml"
  for f in "$chart"/files/dashboards/*.json; do "$YQ" -p json -o yaml '.. | select(has("expr")) | .expr' "$f"; done
} >"$work/exprs.txt"
grep -oE '[A-Za-z_:][A-Za-z0-9_:]*\{[^{]' "$work/exprs.txt" | sed -E 's/\{.$//' | sort -u >"$work/used.txt"
"$YQ" '.groups[].rules[] | select(has("record")) | .record' "$work/rules.yaml" | sort -u >"$work/recorded.txt"
known=$(cat <(grep -v '^#' "$chart/metrics.txt") <(grep -v '^#' "$chart/external-metrics.txt") "$work/recorded.txt" | grep -v '^$' | sort -u)
missing=0
while read -r m; do
  family=$(sed -E 's/_(bucket|sum|count)$//' <<<"$m")
  if ! grep -qxF "$m" <<<"$known" && ! grep -qxF "$family" <<<"$known"; then
    echo "check-observability: unknown metric $m"; missing=$((missing + 1))
  fi
done <"$work/used.txt"
[ "$missing" -eq 0 ] || exit 1
echo "ok ($(wc -l <"$work/used.txt") metrics)"

echo "== telemetry: Loki's and Alloy's configurations"
tel=deploy/k8s/telemetry
LOKI_IMAGE=$("$YQ" '.loki.image' "$tel/values.yaml")
ALLOY_IMAGE=$("$YQ" '.alloy.image' "$tel/values.yaml")
helm template telemetry "$tel" -n monitoring --kube-version "$K8S" -f deploy/environments/homelab/telemetry-values.yaml >"$work/telemetry.yaml"
mkdir -p "$work/loki" "$work/alloy"
"$YQ" 'select(.kind == "ConfigMap" and .metadata.name == "loki") | .data["loki.yaml"]' "$work/telemetry.yaml" >"$work/loki/loki.yaml"
for f in traces logs stages; do
  "$YQ" "select(.kind == \"ConfigMap\" and .metadata.name == \"alloy\") | .data[\"$f.alloy\"]" "$work/telemetry.yaml" >"$work/alloy/$f.alloy"
done
docker run --rm --network none -v "$work/loki:/conf:ro" "$LOKI_IMAGE" -config.file=/conf/loki.yaml -verify-config >"$work/loki.out" 2>&1 ||
  { cat "$work/loki.out"; echo "check-observability: Loki refuses its configuration"; exit 1; }
docker run --rm --network none -e LOG_NAMESPACES=finuance -e LOKI_PUSH_URL=http://loki:3100/loki/api/v1/push \
  -e TEMPO_OTLP_ENDPOINT=http://tempo:4318 -v "$work/alloy:/etc/alloy:ro" "$ALLOY_IMAGE" validate /etc/alloy ||
  { echo "check-observability: Alloy refuses its configuration"; exit 1; }
for f in "$tel"/files/*.alloy "$tel"/tests/*.alloy; do
  docker run --rm --network none -v "$PWD/$tel:/c:ro" "$ALLOY_IMAGE" fmt "/c/${f#"$tel"/}" | diff -q - "$f" >/dev/null ||
    { echo "check-observability: $f is not formatted (alloy fmt)"; exit 1; }
done
echo ok

echo "== telemetry: the log stages on the sample lines"
mkdir -p "$work/stages"
cp "$tel/files/stages.alloy" "$tel/tests/stages_test.alloy" "$work/stages/"
docker run -d --name "$stages_container" --network none --user "$(id -u):$(id -g)" --tmpfs /data \
  -v "$work/stages:/conf:ro" -v "$PWD/$tel/tests:/tests:ro" "$ALLOY_IMAGE" run /conf --storage.path=/data >/dev/null
# as many lines as the expectation has (a stage drops some), then a moment for any line too many
lines=$(grep -c . "$tel/tests/stages.expected" || true)
[ "${UPDATE:-}" = 1 ] && lines=$(cat "$tel"/tests/*.log | grep -c .)
for _ in $(seq 1 60); do
  [ "$(docker logs "$stages_container" 2>&1 | grep -c 'component_id=loki.echo.out labels=')" -ge "$lines" ] && break
  sleep 0.5
done
sleep 1
# what would reach Loki: the labels, the line and its structured metadata (not the time it was read)
docker logs "$stages_container" 2>&1 | grep 'component_id=loki.echo.out labels=' |
  sed -E 's/^.* (labels=)/\1/; s/ entry_timestamp=[^ ]+//' | sort >"$work/stages.out"
docker rm -f "$stages_container" >/dev/null
if [ "${UPDATE:-}" = 1 ]; then cp "$work/stages.out" "$tel/tests/stages.expected"; fi
diff "$tel/tests/stages.expected" "$work/stages.out" || { echo "check-observability: the log stages changed (UPDATE=1 after checking the diff)"; exit 1; }
# the fields THREAT-MODEL §5 names never reach Loki, whatever the expectation says
if grep -E 'detail\\":|query\\":|request: |upstream: |referrer: |\] (DETAIL|STATEMENT|CONTEXT|QUERY):' "$work/stages.out"; then
  echo "check-observability: a field the stages must cut reaches Loki"; exit 1
fi
echo ok
echo "check-observability: ok"
